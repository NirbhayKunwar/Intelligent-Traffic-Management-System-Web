// Helper: Convert Hex to HSL
export function hexToHsl(hex) {
  hex = hex.replace(/^#/, '');
  if (hex.length === 3) {
    hex = hex[0] + hex[0] + hex[1] + hex[1] + hex[2] + hex[2];
  }
  let r = parseInt(hex.substring(0, 2), 16) / 255;
  let g = parseInt(hex.substring(2, 4), 16) / 255;
  let b = parseInt(hex.substring(4, 6), 16) / 255;

  let max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h, s, l = (max + min) / 2;

  if (max === min) {
    h = s = 0;
  } else {
    let d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = (g - b) / d + (g < b ? 6 : 0); break;
      case g: h = (b - r) / d + 2; break;
      case b: h = (r - g) / d + 4; break;
    }
    h /= 6;
  }

  return { h: Math.round(h * 360), s: Math.round(s * 100), l: Math.round(l * 100) };
}

// Helper: Convert HSL to Hex
export function hslToHex(h, s, l) {
  s /= 100;
  l /= 100;
  let c = (1 - Math.abs(2 * l - 1)) * s;
  let x = c * (1 - Math.abs((h / 60) % 2 - 1));
  let m = l - c / 2;
  let r = 0, g = 0, b = 0;

  if (0 <= h && h < 60) {
    r = c; g = x; b = 0;
  } else if (60 <= h && h < 120) {
    r = x; g = c; b = 0;
  } else if (120 <= h && h < 180) {
    r = 0; g = c; b = x;
  } else if (180 <= h && h < 240) {
    r = 0; g = x; b = c;
  } else if (240 <= h && h < 300) {
    r = x; g = 0; b = c;
  } else if (300 <= h && h < 360) {
    r = c; g = 0; b = x;
  }

  let rHex = Math.round((r + m) * 255).toString(16).padStart(2, '0');
  let gHex = Math.round((g + m) * 255).toString(16).padStart(2, '0');
  let bHex = Math.round((b + m) * 255).toString(16).padStart(2, '0');

  return `#${rHex}${gHex}${bHex}`;
}

// Generate Harmony Palette Colors based on Accent and Rule
export function generateHarmonyColors(accentHex, harmonyType, mode) {
  const { h, s, l } = hexToHsl(accentHex);
  
  let baseHue = h;
  let complementaryHue = (h + 180) % 360;
  let analogousHue1 = (h + 30) % 360;
  let analogousHue2 = (h - 30 + 360) % 360;
  let triadicHue1 = (h + 120) % 360;
  let triadicHue2 = (h + 240) % 360;
  let splitHue1 = (h + 150) % 360;
  let splitHue2 = (h + 210) % 360;

  let primaryHue = baseHue;
  let secondaryHue = baseHue;
  
  if (harmonyType === "Complementary") {
    secondaryHue = complementaryHue;
  } else if (harmonyType === "Analogous") {
    secondaryHue = analogousHue1;
  } else if (harmonyType === "Triadic") {
    secondaryHue = triadicHue1;
  } else if (harmonyType === "Split Complementary") {
    secondaryHue = splitHue1;
  }
  
  const isDark = mode === "Dark" || mode === "dark";
  
  if (isDark) {
    return {
      bg: hslToHex(secondaryHue, Math.max(10, Math.round(s * 0.35)), 6),
      panel: hslToHex(secondaryHue, Math.max(10, Math.round(s * 0.35)), 11),
      sidebar: hslToHex(secondaryHue, Math.max(10, Math.round(s * 0.35)), 8),
      border: hslToHex(primaryHue, Math.max(25, Math.round(s * 0.45)), 18),
      text: hslToHex(primaryHue, 10, 94),
      accent: accentHex,
      
      // Expanded fields
      textSecondary: hslToHex(primaryHue, 10, 62),
      inputBg: "rgba(255, 255, 255, 0.05)",
      btnSecondaryBg: "rgba(255, 255, 255, 0.05)",
      btnSecondaryHover: "rgba(255, 255, 255, 0.1)",
      success: "#34d399",
      warning: "#fbbf24",
      error: "#f87171"
    };
  } else {
    // Light Mode
    return {
      bg: hslToHex(secondaryHue, Math.max(5, Math.round(s * 0.15)), 97),
      panel: "#ffffff",
      sidebar: hslToHex(secondaryHue, Math.max(5, Math.round(s * 0.15)), 95),
      border: hslToHex(primaryHue, Math.max(15, Math.round(s * 0.3)), 87),
      text: hslToHex(primaryHue, 15, 12),
      accent: accentHex,
      
      // Expanded fields
      textSecondary: hslToHex(primaryHue, 15, 42),
      inputBg: "rgba(0, 0, 0, 0.02)",
      btnSecondaryBg: "rgba(0, 0, 0, 0.05)",
      btnSecondaryHover: "rgba(0, 0, 0, 0.08)",
      success: "#10b981",
      warning: "#f59e0b",
      error: "#ef4444"
    };
  }
}

// Core applier function that injects CSS variables inline or sets data-theme attributes
export function applyTheme(themeId) {
  if (typeof window === "undefined") return;
  const root = document.documentElement;

  const customVars = [
    "--theme-bg",
    "--theme-card",
    "--theme-border",
    "--theme-text-primary",
    "--theme-text-secondary",
    "--theme-accent",
    "--theme-accent-alt",
    "--theme-accent-hover",
    "--theme-accent-active",
    "--theme-accent-focus",
    "--theme-input-bg",
    "--theme-button-secondary-bg",
    "--theme-button-secondary-hover",
    "--theme-success",
    "--theme-warning",
    "--theme-error",
    "--theme-font",
    "--theme-density-padding",
    "--theme-card-backdrop",
    "--theme-bg-effect-color"
  ];

  if (themeId && themeId.startsWith("custom-")) {
    try {
      const customThemes = JSON.parse(localStorage.getItem("custom-themes") || "[]");
      const theme = customThemes.find(t => t.id === themeId);
      if (theme) {
        root.setAttribute("data-theme", "custom");
        
        const c = theme.colors || {};
        
        const hexToRgb = (hex) => {
          hex = hex.replace(/^#/, '');
          if (hex.length === 3) hex = hex[0]+hex[0]+hex[1]+hex[1]+hex[2]+hex[2];
          const num = parseInt(hex, 16);
          return `${(num >> 16) & 255}, ${(num >> 8) & 255}, ${num & 255}`;
        };

        const adjustColor = (hex, percent) => {
          hex = hex.replace(/^#/, '');
          let num = parseInt(hex, 16);
          let r = (num >> 16) + percent;
          let g = ((num >> 8) & 0x00FF) + percent;
          let b = (num & 0x0000FF) + percent;
          r = Math.min(255, Math.max(0, r));
          g = Math.min(255, Math.max(0, g));
          b = Math.min(255, Math.max(0, b));
          return `#${((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1)}`;
        };

        // Apply colors
        if (c.bg) root.style.setProperty("--theme-bg", c.bg);
        if (c.text) {
          root.style.setProperty("--theme-text-primary", c.text);
          root.style.setProperty("--theme-text-secondary", c.textSecondary || adjustColor(c.text, 40));
        }
        if (c.panel) {
          const frosted = theme.frosted;
          root.style.setProperty(
            "--theme-card", 
            frosted ? `rgba(${hexToRgb(c.panel)}, 0.6)` : c.panel
          );
          root.style.setProperty(
            "--theme-card-backdrop",
            frosted ? "blur(12px)" : "none"
          );
        }
        if (c.border) root.style.setProperty("--theme-border", c.border);
        if (c.accent) {
          root.style.setProperty("--theme-accent", c.accent);
          root.style.setProperty("--theme-accent-alt", adjustColor(c.accent, 20));
          root.style.setProperty("--theme-accent-hover", adjustColor(c.accent, -15));
          root.style.setProperty("--theme-accent-active", adjustColor(c.accent, -30));
          root.style.setProperty("--theme-accent-focus", `rgba(${hexToRgb(c.accent)}, 0.4)`);
        }
        
        if (c.inputBg) root.style.setProperty("--theme-input-bg", c.inputBg);
        if (c.btnSecondaryBg) root.style.setProperty("--theme-button-secondary-bg", c.btnSecondaryBg);
        if (c.btnSecondaryHover) root.style.setProperty("--theme-button-secondary-hover", c.btnSecondaryHover);
        if (c.success) root.style.setProperty("--theme-success", c.success);
        if (c.warning) root.style.setProperty("--theme-warning", c.warning);
        if (c.error) root.style.setProperty("--theme-error", c.error);

        // Apply Font
        let fontFamily = "var(--font-inter)";
        if (theme.font === "Monospace") fontFamily = "var(--font-mono)";
        else if (theme.font === "Poppins") fontFamily = "var(--font-poppins)";
        else if (theme.font === "Roboto") fontFamily = "'Roboto', sans-serif";
        else if (theme.font === "Outfit") fontFamily = "'Outfit', sans-serif";
        else if (theme.font === "System-ui") fontFamily = "system-ui, sans-serif";
        root.style.setProperty("--theme-font", fontFamily);

        // Apply Density
        const density = theme.density || "Comfortable";
        root.setAttribute("data-density", density.toLowerCase());

        // Apply Background Effect
        const effect = theme.bgEffect || "None";
        root.setAttribute("data-bg-effect", effect.toLowerCase());
        if (theme.bgEffectColor) {
          root.style.setProperty("--theme-bg-effect-color", theme.bgEffectColor);
        } else {
          root.style.removeProperty("--theme-bg-effect-color");
        }
        return;
      }
    } catch (err) {
      console.warn("Failed to load custom theme settings:", err);
    }
  }

  // Preset fallback
  root.setAttribute("data-theme", themeId || "original");
  root.removeAttribute("data-density");
  root.removeAttribute("data-bg-effect");
  
  // Clear any inline style overrides
  customVars.forEach(v => root.style.removeProperty(v));
}
